const db = require("../dbModel");
const Beer = db.beer;
const multer = require('multer');

const Op = db.Sequelize.Op;

const storage = multer.diskStorage({
    destination: (req, file, cb) => {
      cb(null, 'uploads/'); // Define the upload directory
    },
    filename: (req, file, cb) => {
      cb(null, Date.now() + '-' + file.originalname); // Generate a unique filename
    },
  });
  
  const upload = multer({
    storage: storage,
    fileFilter: (req, file, cb) => {
      if (file.mimetype.startsWith('image/')) {
        cb(null, true);
      } else {
        cb(new Error('File type not supported'), false);
      }
    },
  });
  
  exports.createBeer = upload.single('image'), async (req, res) => {
    try {
      const newBeer = {
        name: req.body.name,
        photos: req.file.filename, // Save the filename generated by multer
        price: req.body.price,
        description: req.body.description,
        rating: req.body.rating,
      };
  
      const beer = await Beer.create(newBeer);
  
      res.status(201).json(beer); // Respond with the newly created beer
    } catch (error) {
      res.status(500).json({ message: error.message });
    }
  };
  
  exports.findBeerById = async (req, res) => {
    const beerId = req.params.id; // Assuming the beer ID is provided in the route parameter
  
    try {
      const beer = await Beer.findByPk(beerId);
  
      if (!beer) {
        return res.status(404).json({ message: "Beer not found" });
      }
  
      res.status(200).json(beer);
    } catch (error) {
      res.status(500).json({ message: error.message });
    }
  };

  exports.findAll = async (req, res) => {
    try {
      const beers = await Beer.findAll();
      res.json(beers);
    } catch (error) {
      console.error('Error fetching beers:', error);
      res.status(500).json({ error: 'Internal Server Error' });
    }
  };
  
    